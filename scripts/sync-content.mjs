#!/usr/bin/env node
/**
 * Copies the built-in help / policy / checkout text from its source of truth,
 *
 *   server/src/data/defaultContent.js
 *
 * into the two offline copies that ship with the clients:
 *
 *   app/src/data/content.ts                    the regions between // <generated:…> markers
 *                                              (FAQ, the three in-app policies, checkout lines)
 *   admin-dashboard/src/data/builtInContent.ts the whole file (fallback when the server is unreachable)
 *
 * Usage (from the repository root):
 *
 *   node scripts/sync-content.mjs           write the copies
 *   node scripts/sync-content.mjs --check   exit 1 if a copy is out of date (for CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

const {
  DEFAULT_CONTENT_UPDATED_AT,
  LEGAL_DOC_KEYS,
  defaultFaqs,
  defaultLegalDocs,
  defaultPurchaseTerms,
} = await import(join(root, 'server/src/data/defaultContent.js'));

/** The policies the app itself shows (Profile → Policies). The others live on the public website. */
const APP_DOC_KEYS = ['terms', 'refund', 'privacy'];

// ---------------------------------------------------------------- TypeScript literal writer
const quote = (text) => `'${String(text).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
const isIdentifier = (key) => /^[A-Za-z_$][\w$]*$/.test(key);

/** Prettier-like output: one property per line, single quotes, trailing commas. */
function toTs(value, indent = '') {
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[\n${value.map((item) => `${inner}${toTs(item, inner)},`).join('\n')}\n${indent}]`;
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    if (entries.length === 0) return '{}';
    return `{\n${entries
      .map(([key, v]) => `${inner}${isIdentifier(key) ? key : quote(key)}: ${toTs(v, inner)},`)
      .join('\n')}\n${indent}}`;
  }
  if (typeof value === 'string') return quote(value);
  return JSON.stringify(value);
}

/** Replaces the text between `// <generated:name>…` and `// </generated:name>` (markers kept). */
function replaceRegion(source, name, body, file) {
  const open = source.indexOf(`// <generated:${name}>`);
  const close = source.indexOf(`// </generated:${name}>`);
  if (open === -1 || close === -1 || close < open) {
    throw new Error(`${file}: missing the // <generated:${name}> … // </generated:${name}> markers`);
  }
  const openLineEnd = source.indexOf('\n', open) + 1;
  return `${source.slice(0, openLineEnd)}${body}\n${source.slice(close)}`;
}

// ---------------------------------------------------------------- app/src/data/content.ts
const appFile = 'app/src/data/content.ts';
const appFaqs = defaultFaqs.map((faq, index) => ({ id: `f${index + 1}`, question: faq.question, answer: faq.answer }));
const appDocs = Object.fromEntries(APP_DOC_KEYS.map((key) => [key, defaultLegalDocs[key]]));

let appSource = readFileSync(join(root, appFile), 'utf8');
appSource = replaceRegion(appSource, 'faqs', `export const faqs: FaqItem[] = ${toTs(appFaqs)};`, appFile);
appSource = replaceRegion(
  appSource,
  'legal',
  `export const legalDocs: Record<${APP_DOC_KEYS.map((key) => `'${key}'`).join(' | ')}, LegalDoc> = ${toTs(appDocs)};`,
  appFile
);
appSource = replaceRegion(
  appSource,
  'purchase-terms',
  `export const purchaseTerms: string[] = ${toTs(defaultPurchaseTerms)};`,
  appFile
);

// ---------------------------------------------------------------- admin-dashboard/src/data/builtInContent.ts
const adminFile = 'admin-dashboard/src/data/builtInContent.ts';
// The dashboard's editor wants both lists on every section, even when one is empty.
const withBothLists = (doc) => ({
  ...doc,
  sections: doc.sections.map((section) => ({
    heading: section.heading,
    body: section.body ?? [],
    points: section.points ?? [],
  })),
});
const adminContent = {
  faqs: defaultFaqs,
  legalDocs: Object.fromEntries(LEGAL_DOC_KEYS.map((key) => [key, withBothLists(defaultLegalDocs[key])])),
  purchaseTerms: defaultPurchaseTerms,
  legalDocKeys: LEGAL_DOC_KEYS,
  updatedAt: DEFAULT_CONTENT_UPDATED_AT,
};
const adminSource = `// Generated by scripts/sync-content.mjs from server/src/data/defaultContent.js — edit that file, then
// run \`node scripts/sync-content.mjs\`. The dashboard uses this copy only when the server does not answer
// (or is an older deploy without contentDefaults): the Content page still starts from the built-in
// text, and the public policy pages still show a complete document.
import type { ContentDefaults } from '../api/types';

export const BUILT_IN_CONTENT: ContentDefaults = ${JSON.stringify(adminContent, null, 2)};
`;

// ---------------------------------------------------------------- write / check
const outputs = [
  [appFile, appSource],
  [adminFile, adminSource],
];
let stale = 0;
for (const [file, next] of outputs) {
  const path = join(root, file);
  const current = readFileSync(path, 'utf8');
  if (current === next) {
    console.log(`up to date  ${file}`);
    continue;
  }
  stale += 1;
  if (checkOnly) {
    console.log(`OUT OF DATE ${file}`);
  } else {
    writeFileSync(path, next);
    console.log(`written     ${file}`);
  }
}
if (checkOnly && stale) {
  console.error('\nRun `node scripts/sync-content.mjs` and commit the result.');
  process.exit(1);
}
