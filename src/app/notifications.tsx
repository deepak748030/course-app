import { useRouter } from 'expo-router';
import { Bell, BellRing, ChefHat, Clapperboard, Sparkles } from 'lucide-react-native';
import { useEffect } from 'react';
import { Pressable, ScrollView, StyleSheet, Text, View } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';

import { AppText, Badge, EmptyState, ScreenHeader } from '@/components/ui';
import { colors, maxContentWidth, radius, screenPadding, spacing, type } from '@/constants/theme';
import { notifications } from '@/data/content';
import { useStore } from '@/store';
import { minutesAgoLabel } from '@/lib/format';

const kindIcon = {
  'course-update': Clapperboard,
  'learning-reminder': BellRing,
  instructor: ChefHat,
  product: Sparkles,
} as const;

export default function NotificationsScreen() {
  const router = useRouter();
  const insets = useSafeAreaInsets();
  const { state, markNotificationsRead } = useStore();
  const wasUnread = !state.notificationsRead;

  // Opening the screen is the read receipt — the badge on Home clears from here.
  useEffect(() => {
    markNotificationsRead();
  }, [markNotificationsRead]);

  const today = notifications.filter((item) => item.minutesAgo < 60 * 24);
  const earlier = notifications.filter((item) => item.minutesAgo >= 60 * 24);

  return (
    <View style={[styles.root, { paddingTop: insets.top }]}>
      <ScrollView
        contentContainerStyle={[styles.content, { paddingBottom: insets.bottom + spacing.xxl }]}
        showsVerticalScrollIndicator={false}>
        <ScreenHeader title="Notifications" right={wasUnread ? <Badge label="Marked as read" tone="sage" /> : undefined} />

        {notifications.length === 0 ? (
          <EmptyState
            icon={Bell}
            title="Nothing new"
            body="Course updates and learning reminders will appear here."
          />
        ) : (
          <>
            <Group title="Today" items={today} onOpenCourse={(id) => router.push({ pathname: '/course/[id]', params: { id } })} />
            <Group title="Earlier" items={earlier} onOpenCourse={(id) => router.push({ pathname: '/course/[id]', params: { id } })} />
          </>
        )}

        <View style={styles.note}>
          <AppText variant="meta" color={colors.textSecondary}>
            These notifications are sample content generated by the prototype. No push notification service is
            connected, so nothing is delivered outside the app.
          </AppText>
        </View>
      </ScrollView>
    </View>
  );
}

function Group({
  title,
  items,
  onOpenCourse,
}: {
  title: string;
  items: typeof notifications;
  onOpenCourse: (courseId: string) => void;
}) {
  if (items.length === 0) return null;

  return (
    <View style={styles.group}>
      <Text style={[type.section, { color: colors.text }]}>{title}</Text>
      {items.map((item) => {
        const Icon = kindIcon[item.kind];
        const openable = Boolean(item.courseId);
        return (
          <Pressable
            key={item.id}
            accessibilityRole={openable ? 'button' : 'text'}
            accessibilityLabel={`${item.title}. ${item.body}`}
            disabled={!openable}
            onPress={() => item.courseId && onOpenCourse(item.courseId)}
            style={({ pressed }) => [styles.row, pressed && openable && { opacity: 0.8 }]}>
            <View style={styles.icon}>
              <Icon size={18} color={colors.primary} strokeWidth={1.9} />
            </View>
            <View style={styles.flex}>
              <View style={styles.rowHead}>
                <Text style={[type.label, { color: colors.text, flex: 1 }]}>{item.title}</Text>
                <Text style={[type.meta, { color: colors.textSecondary }]}>{minutesAgoLabel(item.minutesAgo)}</Text>
              </View>
              <Text style={[type.supporting, { color: colors.textSecondary }]}>{item.body}</Text>
              {openable ? <Text style={[type.meta, { color: colors.primary }]}>Open course</Text> : null}
            </View>
          </Pressable>
        );
      })}
    </View>
  );
}

const styles = StyleSheet.create({
  root: { flex: 1, backgroundColor: colors.background },
  flex: { flex: 1 },
  content: {
    paddingHorizontal: screenPadding,
    gap: spacing.lg,
    width: '100%',
    maxWidth: maxContentWidth,
    alignSelf: 'center',
  },
  group: { gap: spacing.sm },
  row: {
    flexDirection: 'row',
    gap: spacing.sm,
    backgroundColor: colors.surface,
    borderRadius: radius.card,
    padding: spacing.md,
  },
  rowHead: { flexDirection: 'row', alignItems: 'baseline', gap: spacing.xs },
  icon: {
    width: 40,
    height: 40,
    borderRadius: radius.pill,
    backgroundColor: colors.primarySoft,
    alignItems: 'center',
    justifyContent: 'center',
  },
  note: { marginTop: spacing.xs },
});
